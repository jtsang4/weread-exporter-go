#!/bin/sh
# Writes THIRD_PARTY_NOTICES.md: the licenses of the Go modules that are compiled
# into the weread-exporter binaries. The licenses of BSD and Apache modules ask for
# the notice to travel with binary distributions, so the file is part of every
# release archive and package (see .goreleaser.yaml).
#
#   sh scripts/notices.sh [output-file]      # default: THIRD_PARTY_NOTICES.md
#
# `make notices` runs it, `make notices-check` (and CI) fails when the file is stale.
set -eu

cd "$(dirname "$0")/.."
out="${1:-THIRD_PARTY_NOTICES.md}"
tmp="$(mktemp)"
trap 'rm -f "$tmp" "$tmp.modules"' EXIT

# The dependencies differ between platforms (for example mousetrap is only used on
# Windows), so collect them for every platform of a release.
: >"$tmp.modules"
for goos in linux darwin windows; do
	for goarch in amd64 arm64; do
		CGO_ENABLED=0 GOOS="$goos" GOARCH="$goarch" go list -deps \
			-f '{{if .Module}}{{if not .Module.Main}}{{.Module.Path}}	{{.Module.Dir}}{{end}}{{end}}' \
			./cmd/weread-exporter >>"$tmp.modules"
	done
done
LC_ALL=C sort -u "$tmp.modules" -o "$tmp.modules"

{
	cat <<'EOF'
# Third-party notices

weread-exporter is released under the [MIT License](LICENSE). The binaries contain
the following third-party software, which is used under the terms of its own license.
This file is generated by `scripts/notices.sh`; do not edit it.

The Go standard library is Copyright (c) The Go Authors and is available under a
BSD-3-Clause license: <https://go.dev/LICENSE>.

EOF

	while IFS="$(printf '\t')" read -r path dir; do
		[ -n "$path" ] || continue
		if [ -z "$dir" ] || [ ! -d "$dir" ]; then
			echo "scripts/notices.sh: module $path is not in the module cache (run: go mod download)" >&2
			exit 1
		fi
		files="$(find "$dir" -maxdepth 1 -type f \( -iname 'LICENSE*' -o -iname 'LICENCE*' -o -iname 'COPYING*' -o -iname 'NOTICE*' \) | LC_ALL=C sort)"
		if [ -z "$files" ]; then
			echo "scripts/notices.sh: no license file found for module $path in $dir" >&2
			exit 1
		fi
		printf '## %s\n\n' "$path"
		printf '%s\n' "$files" | while IFS= read -r file; do
			# The backticks are Markdown, not command substitution.
			# shellcheck disable=SC2016
			printf '`%s`:\n\n```text\n' "$(basename "$file")"
			sed -e 's/[[:space:]]*$//' "$file"
			printf '```\n\n'
		done
	done <"$tmp.modules"
} >"$tmp"

mv "$tmp" "$out"
chmod 644 "$out"
echo "wrote $out" >&2
